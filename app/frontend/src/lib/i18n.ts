export type Lang = "ko" | "en" | "zh";

export const LANG_KEY = "peerup_lang";

export function getSavedLang(): Lang | null {
  if (typeof window === "undefined") return null;
  const v = localStorage.getItem(LANG_KEY);
  return v === "ko" || v === "en" || v === "zh" ? v : null;
}

export function saveLang(lang: Lang) {
  if (typeof window !== "undefined") localStorage.setItem(LANG_KEY, lang);
}

/** UI 언어 → BCP-47 로케일. 날짜/시간 포맷에 사용 — 언어 추가 시 여기 한 곳만 고친다. */
export function localeOf(lang: Lang): string {
  return lang === "ko" ? "ko-KR" : lang === "zh" ? "zh-CN" : "en-US";
}

